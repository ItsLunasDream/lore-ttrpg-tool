/**
 * Alle Wörter, unter denen ein Schlagwort zu finden sein soll.
 *
 * Ein unbekanntes Schlagwort — etwa von einem importierten Asset — bleibt wie
 * es ist. Es zu verschlucken wäre schlimmer, als es unübersetzt zu zeigen.
 */
export function tagWords(tag: string): string[] {
  const en = TAG_EN[tag];
  return en ? [tag, ...en] : [tag];
}

/** Anzeige eines Schlagworts in der eingestellten Sprache. */
export function tagLabel(tag: string): string {
  if (getLanguage() === 'de') return tag;
  return TAG_EN[tag]?.[0] ?? tag;
}
